import { useState } from "react";
import { Link } from "@tanstack/react-router";
import { Pause, Play, ScanLine, ArrowUpRight } from "lucide-react";
import { useSimulation } from "@/hooks/use-simulation";
import { Intersection } from "./Intersection";

const PHASE_LABEL = { NS_GREEN: "N–S green", NS_AMBER: "N–S amber", EW_GREEN: "E–W green", EW_AMBER: "E–W amber" };

export function LiveLab() {
  const [running, setRunning] = useState(true);
  const [overlay, setOverlay] = useState(true);
  const snap = useSimulation({ running, seed: 21 });
  const total = snap.passed.N + snap.passed.S + snap.passed.E + snap.passed.W;
  return (
    <div className="grid gap-px border border-border bg-border lg:grid-cols-[1fr_320px]">
      <div className="relative bg-background">
        <span className="absolute left-3 top-3 z-10 flex items-center gap-1.5 bg-warn px-2 py-1 label-mono text-signal-foreground">
          <span className="size-1.5 rounded-full bg-signal-foreground animate-pulse-dot" /> Demo simulation
        </span>
        <Intersection snap={snap} overlay={overlay} className="aspect-square w-full max-h-[620px]" />
      </div>
      <div className="flex flex-col bg-background">
        <div className="flex gap-px border-b border-border bg-border">
          <button onClick={() => setRunning(!running)} aria-pressed={!running} className="flex flex-1 items-center justify-center gap-2 bg-background py-3 text-sm hover:bg-secondary">
            {running ? <Pause className="size-4" /> : <Play className="size-4" />} {running ? "Pause" : "Resume"}
          </button>
          <button onClick={() => setOverlay(!overlay)} aria-pressed={overlay} className={`flex flex-1 items-center justify-center gap-2 py-3 text-sm ${overlay ? "bg-signal text-signal-foreground" : "bg-background hover:bg-secondary"}`}>
            <ScanLine className="size-4" /> Detections
          </button>
        </div>
        <dl className="grid grid-cols-2 gap-px bg-border">
          {[
            ["Signal", PHASE_LABEL[snap.phase]],
            ["Next change", `${snap.phaseRemaining.toFixed(1)}s`],
            ["Tracked now", snap.vehicles.length],
            ["Cleared", total],
            ["Queued", snap.queueTotal],
            ["State", snap.congestion],
          ].map(([k, v]) => (
            <div key={k} className="bg-background p-4">
              <dt className="label-mono text-muted-foreground">{k}</dt>
              <dd className="mt-1.5 font-mono text-lg capitalize">{v}</dd>
            </div>
          ))}
        </dl>
        <p className="mt-auto p-4 text-xs leading-relaxed text-muted-foreground">
          Vehicles, labels and confidence scores are generated by a seeded simulator — no camera or model inference is running.
        </p>
        <Link to="/command-center" className="flex items-center justify-between border-t border-border p-4 text-sm hover:bg-secondary">
          Open full command center <ArrowUpRight className="size-4" />
        </Link>
      </div>
    </div>
  );
}
